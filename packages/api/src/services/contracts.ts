import { and, desc, eq, inArray } from "drizzle-orm";
import {
  ContractDocumentSchema,
  ProposalVersionPayloadSchema,
  contractDocumentDigest,
  CONTRACT_DOCUMENT_SCHEMA_VERSION,
  type ContractDocument,
  type ContractSignatureRecord,
  type StaffContractVersion,
} from "@omnitwin/types";
import { proposalContractSignatures, proposalContractVersions, proposalVersions, proposals, venues } from "../db/schema.js";
import type { Database } from "../db/client.js";
import type { ProposalClient } from "./proposal-client.js";

// ---------------------------------------------------------------------------
// The contract (Plan 19 L5; goal 06 S6): generated by the server from the
// accepted proposal version and the venue's terms, hashed, and never changed.
//
// The document carries the venue, the client the proposal was addressed to
// (name and email, so the email a signature records is part of what is
// signed), the accepted version by number and content hash, the event's
// facts and the quote exactly as accepted, and the terms. Its SHA-256 over
// the canonical JSON is what a signature binds to.
// ---------------------------------------------------------------------------

type Reader = Pick<Database, "select">;
type ProposalRow = typeof proposals.$inferSelect;
type VersionRow = typeof proposalContractVersions.$inferSelect;
type SignatureRow = typeof proposalContractSignatures.$inferSelect;

/** What a contract is generated from: the accepted version and its venue. */
export interface ContractSource {
  readonly proposalTitle: string;
  readonly proposalVersion: number;
  readonly proposalVersionHash: string;
  readonly payload: ReturnType<typeof ProposalVersionPayloadSchema.parse>;
  readonly venue: { readonly name: string; readonly address: string };
}

/** The accepted version and the venue, or null when either cannot be read. */
export async function contractSource(db: Reader, proposal: Pick<ProposalRow, "id" | "venueId" | "status" | "sentVersion">): Promise<ContractSource | null> {
  if (proposal.status !== "accepted" || proposal.sentVersion === null) return null;
  const [version] = await db.select({ payload: proposalVersions.payload, sourceHash: proposalVersions.sourceHash })
    .from(proposalVersions)
    .where(and(eq(proposalVersions.proposalId, proposal.id), eq(proposalVersions.version, proposal.sentVersion)))
    .limit(1);
  const [venue] = await db.select({ name: venues.name, address: venues.address }).from(venues).where(eq(venues.id, proposal.venueId)).limit(1);
  if (version === undefined || venue === undefined) return null;
  const payload = ProposalVersionPayloadSchema.safeParse(version.payload);
  if (!payload.success) return null;
  return {
    proposalTitle: payload.data.title,
    proposalVersion: proposal.sentVersion,
    proposalVersionHash: version.sourceHash,
    payload: payload.data,
    venue,
  };
}

/** The document a new version would be, numbered and dated. */
export function contractDocument(
  source: ContractSource,
  client: { readonly name: string; readonly email: string },
  terms: string,
  contractVersion: number,
  preparedAt: Date,
): ContractDocument {
  return ContractDocumentSchema.parse({
    schemaVersion: CONTRACT_DOCUMENT_SCHEMA_VERSION,
    contractVersion,
    preparedAt: preparedAt.toISOString(),
    venue: source.venue,
    client,
    proposal: { title: source.proposalTitle, version: source.proposalVersion, versionHash: source.proposalVersionHash },
    event: source.payload.facts ?? { eventDate: null, guestCount: null, occasion: null, roomName: null, roomSlug: null },
    quote: source.payload.quote,
    terms,
  });
}

/** The client a contract is with: the addressed client's name (else their email) and email. */
export function contractClient(client: ProposalClient): { readonly name: string; readonly email: string } | null {
  if (client.email === null) return null;
  const name = client.name?.trim() ?? "";
  return { name: name === "" ? client.email : name.slice(0, 200), email: client.email };
}

/** A stored version's document, checked against its own hash; null if it no longer agrees. */
export function storedDocument(row: Pick<VersionRow, "document" | "documentHash">): ContractDocument | null {
  const parsed = ContractDocumentSchema.safeParse(row.document);
  if (!parsed.success) return null;
  return contractDocumentDigest(parsed.data) === row.documentHash ? parsed.data : null;
}

export function signatureRecord(row: SignatureRow): ContractSignatureRecord {
  return {
    signerName: row.signerName,
    signerEmail: row.signerEmail,
    signedAt: row.signedAt.toISOString(),
    documentHash: row.documentHash,
    consentStatement: row.consentStatement,
    userAgent: row.userAgent,
    shareTokenPrefix: row.shareTokenPrefix,
  };
}

/** The newest version of a proposal's contract. */
export async function latestContractVersion(db: Reader, proposalId: string): Promise<VersionRow | undefined> {
  const [row] = await db.select().from(proposalContractVersions)
    .where(eq(proposalContractVersions.proposalId, proposalId))
    .orderBy(desc(proposalContractVersions.version))
    .limit(1);
  return row;
}

/** Every version, newest first, with its signature. A version whose document no longer matches its hash is left out and reported. */
export async function staffContractVersions(db: Reader, proposalId: string, onCorrupt: (id: string) => void): Promise<StaffContractVersion[]> {
  const rows = await db.select().from(proposalContractVersions)
    .where(eq(proposalContractVersions.proposalId, proposalId))
    .orderBy(desc(proposalContractVersions.version));
  if (rows.length === 0) return [];
  const signatures = await db.select().from(proposalContractSignatures)
    .where(inArray(proposalContractSignatures.contractVersionId, rows.map((row) => row.id)));
  const views: StaffContractVersion[] = [];
  for (const row of rows) {
    const document = storedDocument(row);
    if (document === null) { onCorrupt(row.id); continue; }
    const signature = signatures.find((candidate) => candidate.contractVersionId === row.id);
    views.push({
      id: row.id,
      version: row.version,
      proposalVersion: row.proposalVersion,
      document,
      documentHash: row.documentHash,
      createdAt: row.createdAt.toISOString(),
      createdByLabel: row.createdByLabel,
      signature: signature === undefined ? null : signatureRecord(signature),
    });
  }
  return views;
}
