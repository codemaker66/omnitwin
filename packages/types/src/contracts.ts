import { z } from "zod";
import {
  CanonicalJsonValueSchema,
  sha256Hex,
  stableCanonicalJson,
} from "./canonical-layout-snapshot.js";
import { ProposalFactsSchema, QuoteSnapshotSchema } from "./proposal.js";

// ---------------------------------------------------------------------------
// The contract and its electronic signature (Plan 19 L5; goal 06 S6).
//
// A simple electronic signature under the Electronic Communications Act 2000
// s.7: the client reads one exact version of the contract, types their name,
// ticks a statement that doing so signs it, and presses Sign. The record keeps
// what makes it evidence: the name typed, the email of the client the venue
// addressed the proposal to, the moment, the SHA-256 of the exact document
// signed, the browser's user agent and the words they agreed to. No IP
// address is kept.
//
// A contract version is generated by the server from the accepted proposal
// version (its quote and the event's facts, frozen when it was saved) and the
// terms the venue sets, so nothing is retyped (pain point 1) and the contract
// cannot drift from what was accepted (pain point 4). Versions and signatures
// are immutable in the database; a change makes a new version, which is
// signed afresh, and the earlier signature stays on the record of the version
// it signed.
// ---------------------------------------------------------------------------

export const CONTRACT_DOCUMENT_SCHEMA_VERSION = "venviewer.contract.v1";
export const CONTRACT_DOCUMENT_DIGEST_DOMAIN_PREFIX = "venviewer.contract.v1:";

/** The statement a client ticks to sign. Kept word for word with every signature. */
export const CONTRACT_CONSENT_STATEMENT =
  "I have read this contract and agree to its terms. I understand that typing my name and pressing Sign is my electronic signature, and that it binds me as my handwritten signature would.";

export const MAX_CONTRACT_TERMS_LENGTH = 20_000;
export const MAX_SIGNER_NAME_LENGTH = 200;
export const MAX_SIGNATURE_USER_AGENT_LENGTH = 512;

const Sha256Hex = z.string().regex(/^[a-f0-9]{64}$/u, "Hash must be 64 lowercase hex characters");

export const ContractDocumentSchema = z.object({
  schemaVersion: z.literal(CONTRACT_DOCUMENT_SCHEMA_VERSION),
  contractVersion: z.number().int().positive(),
  /** When the venue prepared this version. */
  preparedAt: z.iso.datetime({ offset: true }),
  venue: z.object({ name: z.string().min(1).max(200), address: z.string().max(500) }).strict(),
  /** Who the contract is with: the client the proposal was addressed to. */
  client: z.object({ name: z.string().min(1).max(200), email: z.email().max(255) }).strict(),
  /** The proposal version the client accepted, by number and content hash. */
  proposal: z.object({ title: z.string().min(1).max(200), version: z.number().int().positive(), versionHash: Sha256Hex }).strict(),
  event: ProposalFactsSchema,
  quote: QuoteSnapshotSchema.nullable(),
  terms: z.string().min(1).max(MAX_CONTRACT_TERMS_LENGTH),
}).strict();
export type ContractDocument = z.infer<typeof ContractDocumentSchema>;

/** Domain-prefixed SHA-256 of the document's stable canonical JSON. */
export function contractDocumentDigest(document: ContractDocument): string {
  const canonical = CanonicalJsonValueSchema.parse(document);
  return sha256Hex(`${CONTRACT_DOCUMENT_DIGEST_DOMAIN_PREFIX}${stableCanonicalJson(canonical)}`);
}

/** Whether two documents say the same thing, whatever their number and date. */
export function sameContractContent(a: ContractDocument, b: ContractDocument): boolean {
  const content = ({ contractVersion: _v, preparedAt: _p, ...rest }: ContractDocument) => stableCanonicalJson(CanonicalJsonValueSchema.parse(rest));
  return content(a) === content(b);
}

/** The venue prepares a version: its terms, against the accepted version the screen showed. */
export const PrepareContractSchema = z.object({
  terms: z.string().trim().min(1).max(MAX_CONTRACT_TERMS_LENGTH),
  version: z.number().int().positive(),
}).strict();
export type PrepareContract = z.infer<typeof PrepareContractSchema>;

/** The client signs the exact version and document their page showed. */
export const SignContractSchema = z.object({
  contractVersion: z.number().int().positive(),
  documentHash: Sha256Hex,
  signerName: z.string().trim().min(1).max(MAX_SIGNER_NAME_LENGTH),
  consent: z.literal(true),
}).strict();
export type SignContract = z.infer<typeof SignContractSchema>;

const IsoDate = z.iso.datetime({ offset: true });

export const ClientContractViewSchema = z.object({
  consentStatement: z.string(),
  contract: z.object({
    version: z.number().int().positive(),
    document: ContractDocumentSchema,
    documentHash: Sha256Hex,
    signature: z.object({ signerName: z.string(), signedAt: IsoDate }).strict().nullable(),
  }).strict().nullable(),
}).strict();
export type ClientContractView = z.infer<typeof ClientContractViewSchema>;

export const ContractSignatureRecordSchema = z.object({
  signerName: z.string(),
  signerEmail: z.string(),
  signedAt: IsoDate,
  documentHash: Sha256Hex,
  consentStatement: z.string(),
  userAgent: z.string().nullable(),
  /** The first characters of the link it was signed through. */
  shareTokenPrefix: z.string().nullable(),
}).strict();
export type ContractSignatureRecord = z.infer<typeof ContractSignatureRecordSchema>;

export const StaffContractVersionSchema = z.object({
  id: z.uuid(),
  version: z.number().int().positive(),
  proposalVersion: z.number().int().positive(),
  document: ContractDocumentSchema,
  documentHash: Sha256Hex,
  createdAt: IsoDate,
  createdByLabel: z.string().nullable(),
  signature: ContractSignatureRecordSchema.nullable(),
}).strict();
export type StaffContractVersion = z.infer<typeof StaffContractVersionSchema>;

/** The staff view: every version, newest first, and what a new one would take. */
export const StaffContractViewSchema = z.object({
  /** The accepted proposal version a new contract version would embody. */
  acceptedVersion: z.number().int().positive().nullable(),
  /** The client's email of record; a contract cannot be prepared without one. */
  clientEmail: z.string().nullable(),
  versions: z.array(StaffContractVersionSchema),
}).strict();
export type StaffContractView = z.infer<typeof StaffContractViewSchema>;
